CREATE DATABASE IF NOT EXISTS mymandado;

USE mymandado;

-- USERS
CREATE TABLE IF NOT EXISTS USERS(
	usr_id INT AUTO_INCREMENT PRIMARY KEY NOT NULL,
	usr_role INT NOT NULL DEFAULT 0,
	usr_name VARCHAR(30) NOT NULL UNIQUE,
  usr_hashword VARCHAR(255) NOT NULL
	) ENGINE = InnoDB;

-- PRODUCTS
CREATE TABLE IF NOT EXISTS PRODUCTS(
	prd_id INT AUTO_INCREMENT PRIMARY KEY NOT NULL,
	prd_name VARCHAR(30) NOT NULL UNIQUE,
	prd_unit VARCHAR(10)
	)ENGINE = InnoDB;

-- CART 
CREATE TABLE IF NOT EXISTS CART(
  car_id INT AUTO_INCREMENT PRIMARY KEY NOT NULL,
  car_crtnb INT NOT NULL DEFAULT 0,
  car_usrid INT NOT NULL,
  car_name VARCHAR(30),
  car_desc VARCHAR(100),

  UNIQUE (car_usrid,car_crtnb),
  FOREIGN KEY (car_usrid) REFERENCES USERS(usr_id) ON DELETE CASCADE ON UPDATE CASCADE
) Engine = InnoDB;


-- CART_ITEMS
CREATE TABLE IF NOT EXISTS CART_ITEMS(
	crt_id INT AUTO_INCREMENT PRIMARY KEY NOT NULL,
	crt_usrid INT NOT NULL,
  crt_crtnb INT NOT NULL,
	crt_prdid INT NOT NULL,
	crt_qtty INT NOT NULL DEFAULT 0,
	crt_isdone  BOOLEAN DEFAULT FALSE,

  UNIQUE (crt_usrid,crt_crtnb,crt_prdid),
  FOREIGN KEY (crt_usrid,crt_crtnb) REFERENCES CART(car_usrid,car_crtnb) ON DELETE CASCADE ON UPDATE CASCADE,
	FOREIGN KEY (crt_prdid) REFERENCES PRODUCTS(prd_id) ON DELETE CASCADE ON UPDATE CASCADE
	) Engine = InnoDB;

-- CART_SHARES
CREATE TABLE IF NOT EXISTS CART_SHARES(
	csh_id INT AUTO_INCREMENT PRIMARY KEY NOT NULL,
	csh_carid INT NOT NULL,
	csh_usrid INT NOT NULL,

	UNIQUE (csh_carid,csh_usrid),
	FOREIGN KEY (csh_carid) REFERENCES CART(car_id) ON DELETE CASCADE ON UPDATE CASCADE,
	FOREIGN KEY (csh_usrid) REFERENCES USERS(usr_id) ON DELETE CASCADE ON UPDATE CASCADE
	) Engine = InnoDB;

-- USER_EXCLUSIONS
CREATE TABLE IF NOT EXISTS PRODUCTS_EXCLUSIONS(
	xld_userid INT NOT NULL,
	xld_prdid INT NOT NULL,

	CONSTRAINT fk_exclude_user FOREIGN KEY (xld_userid) REFERENCES USERS(usr_id) ON DELETE CASCADE ON UPDATE CASCADE,
	CONSTRAINT fk_exclude_prd FOREIGN KEY (xld_prdid) REFERENCES PRODUCTS(prd_id) ON DELETE CASCADE ON UPDATE CASCADE
	) Engine = InnoDB;
